#include <stdio.h>
#include <string.h>
#include <math.h>
#include <stdlib.h>

int main() {
    long long n = 1;
    long long n1 = 2;
    long long n2 = 4;
    long long n3 = 8;
    scanf("%d", &n);
    scanf("%d", &n1);
    scanf("%d", &n2);
    scanf("%d", &n3);
    
    n = n * 0;
    n1 = n1 * n1;
    n2 = n2 * n2;
    n3 = n3 * n3;
    printf("%d\n", n);
    printf("%d\n", n1);
    printf("%d\n", n2);    
    printf("%d\n", n3);
}
